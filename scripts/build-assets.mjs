// Bundles the cleaned SVG drafts in src/client/ui/assets/svg into plain TS modules
// (src/client/ui/assets/generated/*.ts, git-ignored). The generated modules are framework-free
// string maps, so Storybook, Vitest and the esbuild client bundle import them the same way.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const svgDir = path.join(root, 'src/client/ui/assets/svg');
const outDir = path.join(root, 'src/client/ui/assets/generated');
fs.mkdirSync(outDir, { recursive: true });

const PLANES = ['narrowbody', 'widebody', 'jumbo-hump', 'double-decker', 'regional-jet', 'turboprop', 'business-jet', 'light-aircraft', 'glider', 'helicopter'];
const read = (f) => fs.readFileSync(path.join(svgDir, f), 'utf8').trim();

const planes = Object.fromEntries(PLANES.map((p) => [p, read(`${p}.svg`)]));

const skies = {};
for (const f of fs.readdirSync(svgDir).filter((f) => /^sky-.*\.svg$/.test(f)).sort()) skies[f.slice(4, -4)] = read(f);

// Logos reference a sibling PNG. Inline it as data URI; a missing PNG becomes a dashed placeholder.
const missing = [];
const logos = {};
for (const f of fs.readdirSync(path.join(svgDir, 'logos')).filter((f) => f.endsWith('.svg')).sort()) {
  let svg = read(`logos/${f}`);
  svg = svg.replace(/<image\b([^>]*?)href="([^"]+)"([^>]*)>(<\/image>)?/, (m, a, href, b) => {
    const png = path.join(svgDir, 'logos', href);
    const attrs = `${a} ${b}`;
    if (fs.existsSync(png)) return `<image${a}href="data:image/png;base64,${fs.readFileSync(png).toString('base64')}"${b}></image>`;
    missing.push(f);
    const g = (n) => (attrs.match(new RegExp(`\\b${n}="([^"]+)"`)) || [])[1];
    return `<rect data-missing-asset="${href}" x="${g('x')}" y="${g('y')}" width="${g('width')}" height="${g('height')}" fill="none" stroke="#5B6670" stroke-dasharray="4 3" stroke-width="1.5"></rect>`;
  });
  logos[f.slice(0, -4)] = svg;
}

const emit = (name, exportName, obj, comment, type = 'Record<string, string>') =>
  fs.writeFileSync(path.join(outDir, `${name}.ts`), `// GENERATED by scripts/build-assets.mjs - do not edit. ${comment}\nexport const ${exportName}: ${type} = ${JSON.stringify(obj)};\n`);
emit('planes', 'PLANE_SVG', planes, 'Unpainted plane silhouettes by type class.');
emit('skies', 'SKY_SVG', skies, 'Skies keyed "<time>-<weather>".');
emit('logos', 'LOGO_SVG', logos, 'Logos keyed by file name.');
if (missing.length) console.warn(`[assets] logo PNG missing, placeholder used: ${missing.join(', ')}`);
console.log(`[assets] ${Object.keys(planes).length} planes, ${Object.keys(skies).length} skies, ${Object.keys(logos).length} logos`);

// ---- Livery layer model (ADR 0031/0032): silhouette + details per Typklasse, livery files, generated stories ----
const planesDir = path.join(root, 'src/client/ui/assets/planes');
const liveriesDir = path.join(root, 'src/client/ui/assets/liveries');
const groupInner = (svg, id) => (svg.match(new RegExp(`<g id="${id}">([\\s\\S]*?)</g>`)) || [])[1]?.trim();
const pathD = (svg, id) => (svg.match(new RegExp(`<path id="${id}" d="([^"]+)"`)) || [])[1];
const planeParts = {};
if (fs.existsSync(planesDir)) {
  for (const t of fs.readdirSync(planesDir).sort()) {
    const sil = path.join(planesDir, t, 'silhouette.svg');
    const det = path.join(planesDir, t, 'details.svg');
    if (!fs.existsSync(sil) || !fs.existsSync(det)) continue;
    const svg = read(`../planes/${t}/silhouette.svg`);
    const fields = {};
    for (const f of ['engines', 'wings', 'tailplane']) { const g = groupInner(svg, `field-${f}`); if (g) fields[f] = g; }
    const fuselage = pathD(svg, 'outline-fuselage');
    const fin = pathD(svg, 'outline-fin');
    const outlines = fuselage && fin ? { fuselage, fin } : undefined; // absent: #body doubles as the outline
    planeParts[t] = { viewBox: svg.match(/viewBox="([^"]+)"/)[1], body: groupInner(svg, 'body'), fields, ...(outlines ? { outlines } : {}), details: groupInner(read(`../planes/${t}/details.svg`), 'details') };
  }
}
emit('plane-parts', 'PLANE_PARTS', planeParts, 'Silhouette body/fields and details per Typklasse (ADR 0032).', 'Record<string, { viewBox: string; body: string; fields: Record<string, string>; outlines?: { fuselage: string; fin: string }; details: string }>');

const liveryFiles = {};
if (fs.existsSync(liveriesDir)) {
  for (const id of fs.readdirSync(liveriesDir).sort()) {
    const dir = path.join(liveriesDir, id);
    if (!fs.statSync(dir).isDirectory()) continue;
    for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) liveryFiles[`${id}/${f.slice(0, -5)}`] = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  }
}
emit('liveries', 'LIVERY_FILES', liveryFiles, 'Livery files keyed "<liveryId>/<typklasse>" (also the index of which combinations exist).', 'Record<string, unknown>');

// Storybook cannot create stories at runtime, so one story per livery file is generated here (ADR 0034: the shown livery keeps its story).
const camel = (k) => k.replace(/[^a-z0-9]+(.)?/gi, (_m, c) => (c ? c.toUpperCase() : ''));
const storyLines = Object.keys(liveryFiles).map((k) => {
  const [id, typ] = k.split('/');
  return `export const ${camel(k)}: StoryObj = { name: ${JSON.stringify(`${id} – ${typ}`)}, render: () => show(${JSON.stringify(k)}) };`;
});
fs.writeFileSync(path.join(outDir, 'liveries.stories.ts'), `// GENERATED by scripts/build-assets.mjs - do not edit. One story per livery file (ADR 0032/0034).
import type { Meta, StoryObj } from '@storybook/html-vite';
import { h } from '../../dom';
import { renderLiverySvg } from '../../domain/livery-render';
import { LiveryFileSchema } from '../../domain/livery-file';
import { LIVERY_FILES } from './liveries';

const meta: Meta = { title: 'Liveries/Pfade' };
export default meta;

const show = (key: string): HTMLElement =>
  h('div', { class: 'pa-plane-backdrop', style: 'max-width:720px' }, h('div', { html: renderLiverySvg(LiveryFileSchema.parse(LIVERY_FILES[key])) }));

${storyLines.length ? storyLines.join('\n') : 'export const Leer: StoryObj = { name: "keine Lackierungsdateien", render: () => h("div", { text: "keine Lackierungsdateien" }) };'}
`);
console.log(`[assets] ${Object.keys(planeParts).length} plane silhouettes, ${Object.keys(liveryFiles).length} livery files`);
